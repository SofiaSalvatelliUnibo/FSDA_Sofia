%% Embedding 1: tf-idf and singular value decomposition (LSA)
% The classical embedding. The matrix of the tf-idf weights of the words is
% reduced to p dimensions with the singular value decomposition, and the rows
% are normalised. It needs no toolbox, and only knows which words appear in a
% document. Words of at least 3 letters are used, without those which
% appear in a single document or in more than half of them.
rng(1)
p=20;
tok=cellfun(@(x) regexp(lower(x),'[a-z]{3,}','match'),docs,'UniformOutput',false);
allw=[tok{:}];
[vocab,~,wid]=unique(allw);
docid=repelem((1:n)',cellfun(@numel,tok));
TF=sparse(docid,wid,1,n,numel(vocab));
