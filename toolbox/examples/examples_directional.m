%% DOCUMENT EMBEDDINGS

%% What is a document embedding? A primer for statisticians
% A neural network, trained on an enormous collection of texts, turns a
% document into a vector of p numbers (p=384, 768, 1536, ...), its
% "embedding". The training makes texts which are used in similar contexts
% have similar vectors, so that two documents about the same subject point in
% similar directions even when they use different words.
%  - Only the direction is meaningful. The similarity of two documents is the
%    cosine of the angle between their vectors, and the length of the vectors
%    is an artefact of the network (and of the length of the text). The
%    vectors are therefore normalised to length 1: the data are points of
%    the unit hypersphere, the space of the functions of this suite.
%  - A "topic" is a group of documents whose directions are concentrated
%    around a mean direction: this is exactly a von Mises-Fisher group.
%    Documents which are about nothing in particular, or about subjects
%    not in the collection, are scattered everywhere: this is the uniform
%    noise component, or the units which are trimmed.
%  - Two features of real embeddings matter for the statistics:
%    (1) anisotropy: the vectors tend to lie in a narrow cone around a
%        common direction, so that two unrelated documents have a cosine
%        which is far from 0. Subtracting the mean and normalising again
%        removes the cone (it is the usual "centring", see Mu and Viswanath,
%        2018);
%    (2) the number of directions that really carry information (the
%        topics) is much smaller than p, while the sampling noise lives in
%        all the p directions. The next sections show how this affects the
%        estimates and how the dimension can be reduced.
%  - There are two families of embeddings: static ones (word2vec, GloVe:
%    one vector for each word, a document is the average of its words) and
%    contextual ones (transformers: sentence-BERT, the models of large
%    language models: one vector for the whole text, which depends on the
%    order of the words). The function docembed computes both with Python;
%    the older tf-idf with a singular value decomposition (latent semantic
%    analysis, LSA) is used as a baseline.

%% A workflow for document embeddings (simulated data)
% This simulation reproduces the features above: 4 topics (vMF groups), 60
% documents without topic (uniform), and a common direction added to all the
% documents (anisotropy). The analysis shows the three steps of any real
% application: (1) centring and normalising, (2) fit with a noise component
% and a small trimming level, (3) reading the topics.
clearvars;close all;
rng(3)
p=100; k=4;
topicdir=randn(k,p);
topicdir=topicdir./vecnorm(topicdir,2,2);
common=randn(1,p); common=common/norm(common);
Y=[vMFrnd(100,topicdir(1,:),40); vMFrnd(100,topicdir(2,:),40); ...
   vMFrnd(100,topicdir(3,:),40); vMFrnd(100,topicdir(4,:),40); ...
   vMFrnd(60,common,0)];
topic=[repelem((1:k)',100); zeros(60,1)];
Y=Y+2*common;                      % anisotropy
Y=Y./vecnorm(Y,2,2);
C=Y*Y';
fprintf('Mean cosine between documents: %.2f\n',mean(C(triu(true(size(Y,1)),1))));

% (1) Centring and renormalisation
Yc=Y-mean(Y,1);
Yc=Yc./vecnorm(Yc,2,2);
C=Yc*Yc';
fprintf('Mean cosine after centring:    %.2f\n',mean(C(triu(true(size(Yc,1)),1))));

% (2) Fit with a noise component and a small trimming level. Here k*(p+1) is
% larger than n/2, therefore init='auto' uses k-means++.
out=tclustvmf(Yc,k,0.01,10,'noise',true,'nsamp',100,'plots',1);
disp('Groups: 0 trimmed, 1-4 topics, 5 background')
disp(out.siz)
fprintf('Estimated proportion of background %.3f (true 0.13)\n',out.noiseprop);
disp('Estimated concentrations:'), disp(out.kappaopt')

% (3) Reading a topic: the documents closest to its direction
for j=1:k
    [~,ord]=sort(Yc*out.muopt(j,:)','descend');
    fprintf('Topic %d: closest documents %s, true topics %s\n',j, ...
        mat2str(ord(1:5)'),mat2str(topic(ord(1:5))'));
end

% The documents explained by the noise component or trimmed are often the
% most informative to read: they are off-topic or unusual
offtopic=find(out.idx==0 | out.idx==k+1);
fprintf('Documents to inspect: %d (true documents without topic among them: %d)\n', ...
    numel(offtopic),sum(topic(offtopic)==0));

%% High dimension and few documents: the concentration is overestimated
% Is it legitimate to fit a vMF group in p=384 dimensions with a few dozen
% documents? The model is well defined in any dimension, but the estimate
% of kappa is biased upwards when the number of documents n_j in a group is
% small with respect to p. Reason: for uniform data (kappa=0) the mean
% resultant length is not 0 but about 1/sqrt(n_j) in any dimension, and
% kappa is estimated as about p*r. The table gives the estimate of kappa
% for samples from the uniform distribution (true kappa=0).
clearvars;close all;
rng(1)
pp=[3 20 100 384];
nj=[20 40 100 1000 10000];
kap=zeros(numel(pp),numel(nj));
for i=1:numel(pp)
    for j=1:numel(nj)
        Y=vMFrnd(nj(j),ones(1,pp(i)),0);
        kap(i,j)=vMFkappa(norm(mean(Y,1)),pp(i));
    end
end
disp(array2table(kap,'RowNames',compose('p=%d',pp),'VariableNames',compose('nj%d',nj)))
% Comment: with p=384 and 40 documents per group the estimate of kappa is
% about 60 for data which have no structure at all; with 10000 documents it
% is below 4. The restriction on kappa limits the ratio between the groups
% but not a bias which is common to all of them. Two remedies: more
% documents per group, or a reduction of the dimension, which removes
% most of the directions in which there is only noise (next sections).

%% Real documents: the help pages of FSDA and of MATLAB
