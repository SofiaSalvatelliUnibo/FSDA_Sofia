keep=df>=2 & df<=0.5*n;
TF=TF(:,keep); df=df(keep); vocab=vocab(keep);
X=spfun(@(x) 1+log(x),TF)*spdiags(log(n./df(:)),0,numel(df),numel(df));
nrm=sqrt(sum(X.^2,2));
% a document without any retained word has no direction and is removed
empty=nrm==0;
if any(empty)
    fprintf('Documents without retained words, removed: %s\n',strjoin(docname(empty)',' '))
    X(empty,:)=[]; nrm(empty)=[]; docs(empty)=[]; docname(empty)=[]; theme(empty)=[];
    n=numel(docs);
end
X=spdiags(1./nrm,0,n,n)*X;
[U,S]=svds(X,p);
Z=U*S;
Z=Z./vecnorm(Z,2,2);
C=Z*Z';
fprintf('Mean cosine between documents: %.2f\n',mean(C(triu(true(n),1))));
% The first singular vector is common to all the documents (cone): centre
Z=Z-mean(Z,1);
Z=Z./vecnorm(Z,2,2);
C=Z*Z';
fprintf('Mean cosine after centring:    %.2f\n',mean(C(triu(true(n),1))));

% Clustering: one group for each theme, a noise component for the documents
% which belong to none of them, and a small trimming level.
out=tclustvmf(Z,k,0.02,10,'noise',true,'nsamp',100,'init','kmeans++','plots',1);
tab=accumarray([theme out.idx+1],1,[numel(themename) k+2]);
disp(array2table(tab,'RowNames',themename(:), ...
    'VariableNames',[{'trimmed'} compose('g%d',1:k) {'noise'}]))
sel=out.idx>0 & out.idx<=k & theme~=4;
ariLSA=RandIndexFS(theme(sel),out.idx(sel));
fprintf('Adjusted Rand index (units in a group, without utilities): %.3f\n',ariLSA);
% What is a group about? The words with the largest mean tf-idf
for j=1:k
    m=full(mean(X(out.idx==j,:),1));
    [~,o]=sort(m,'descend');
    fprintf('Group %d (%3d documents, kappa=%5.1f): %s\n',j,sum(out.idx==j), ...
        out.kappaopt(j),strjoin(vocab(o(1:6)),', '));
end
