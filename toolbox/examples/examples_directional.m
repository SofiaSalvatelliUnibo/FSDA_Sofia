C=Ec*Ec';
fprintf('Mean cosine after centring:    %.2f\n',mean(C(triu(true(n),1))));
% With n documents the centred matrix has rank at most n-1: the dimension
% (384) is larger than the number of documents, and tclustvmf stops with the
