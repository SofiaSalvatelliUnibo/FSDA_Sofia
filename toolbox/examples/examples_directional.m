%% Does the reduction of the dimension matter?
% Reducing the dimension with the principal components of the centred
% embeddings is common (the same is done, with other methods, by the topic
% modelling tools based on embeddings), but it is a choice which has to be
% justified, not a free lunch: the principal components are the directions of
% largest variance, which are those in which the topics differ if the topics
% are the main source of variability, and it is not guaranteed. Here the
% number of components p is varied, for the sentence transformer. The
% table gives the share of variance retained, the adjusted Rand index of the
% trimmed vMF clustering and, as a reference, that of spherical k-means
% (restrfactor=1, no trimming, no noise). With a few hundred documents the
% differences between neighbouring values of p are within the variability of
% a run, and p cannot be larger than the number of documents minus 1: for a
% reliable answer a large collection is needed (see the note on the
% experimentation with many documents).
pall=[5 10 20 50 100 200];
pall=pall(pall<n-1);
s2=diag(S).^2;
res=zeros(numel(pall),3);
for i=1:numel(pall)
    rng(1)
    Zp=U(:,1:pall(i))*S(1:pall(i),1:pall(i));
    Zp=Zp./vecnorm(Zp,2,2);
    outp=tclustvmf(Zp,k,0.02,10,'noise',true,'nsamp',50,'init','kmeans++','msg',0);
    outk=tclustvmf(Zp,k,0,1,'nsamp',50,'init','kmeans++','msg',0);
    sp=outp.idx>0 & outp.idx<=k & theme~=4;
    sk=outk.idx>0 & theme~=4;
    res(i,:)=[100*sum(s2(1:pall(i)))/sum(s2) RandIndexFS(theme(sp),outp.idx(sp)) ...
        RandIndexFS(theme(sk),outk.idx(sk))];
end
disp(array2table(res,'RowNames',compose('p=%d',pall), ...
    'VariableNames',{'variance_pct','ARI_vMF_trimmed','ARI_spherical_kmeans'}))
