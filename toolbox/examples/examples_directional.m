fprintf('Trimmed or noise documents (%d): %s\n',numel(odd),strjoin(docname(odd)',' '));

%% Embedding 2: a sentence transformer, computed with Python
% docembed calls Python (a sentence transformer by default: the model
% all-MiniLM-L6-v2, 384 dimensions; other models and backends are options
% of the function) and returns the n-by-p matrix of embeddings, with rows
% of length 1. The first time the model is downloaded (about 90 MB) and
